export function randomReminderMessage(daySeed?: string): string {
  if (!daySeed) {
    return STUDY_REMINDER_MESSAGES[Math.floor(Math.random() * STUDY_REMINDER_MESSAGES.length)];
  }
  let h = 0;
  for (let i = 0; i < daySeed.length; i++) h = (h + daySeed.charCodeAt(i) * 31) | 0;
  return STUDY_REMINDER_MESSAGES[Math.abs(h) % STUDY_REMINDER_MESSAGES.length];
}
